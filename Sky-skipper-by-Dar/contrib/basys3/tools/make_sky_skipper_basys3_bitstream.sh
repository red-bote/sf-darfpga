#!/bin/bash
# Bitstream wrapper for the Sky Skipper Basys3 port. Delegates to the shared
# darfpga_build_bitstream() in sf-darfpga/tools/lib/darfpga-bitstream.sh.
#
# Usage: make_sky_skipper_basys3_bitstream.sh {synth|bitstream}

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../../.." && pwd)"
. "$ROOT/../tools/lib/darfpga-bitstream.sh"

darfpga_build_bitstream \
  --root       "$ROOT" \
  --src-dir    vhdl_sky_skipper_rev_01_2020_01_28 \
  --top-entity sky_skipper_basys3 \
  -- "${1:-}"
